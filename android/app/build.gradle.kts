// Release signing: android/key.properties (local, git-ignored) or environment
// variables (CI). Without either, release builds fall back to debug signing so
// `flutter run --release` keeps working. See docs/ANDROID_RELEASE.md.
val keyProps = Properties().apply {
    val f = rootProject.file("key.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(prop: String, env: String): String? =
    keyProps.getProperty(prop) ?: System.getenv(env)
